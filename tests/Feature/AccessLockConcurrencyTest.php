<?php

namespace Tests\Feature;

use App\Services\Access\AccessMutation;
use Illuminate\Database\QueryException;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

class AccessLockConcurrencyTest extends TestCase
{
    use RefreshDatabase;

    public function test_access_mutations_serialize_on_the_same_role_rows(): void
    {
        $database = config('database.connections.pgsql.database');
        $this->assertIsString($database);
        $this->assertStringEndsWith('_test', $database);

        $original = DB::getDefaultConnection();
        $schema = 'access_lock_'.bin2hex(random_bytes(6));
        config()->set('database.connections.pgsql_access_a', config('database.connections.pgsql'));
        config()->set('database.connections.pgsql_access_b', config('database.connections.pgsql'));
        $first = DB::connection('pgsql_access_a');
        $second = DB::connection('pgsql_access_b');
        $first->statement("CREATE SCHEMA {$schema}");

        try {
            $first->statement("CREATE TABLE {$schema}.roles (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(255) NOT NULL, name varchar(255) NOT NULL)");
            $first->statement("INSERT INTO {$schema}.roles (code, name) VALUES ('admin', 'Administrator')");
            $first->statement("SET search_path TO {$schema}");
            $second->statement("SET search_path TO {$schema}");
            $second->statement("SET lock_timeout TO '200ms'");

            DB::setDefaultConnection('pgsql_access_a');
            $first->beginTransaction();
            app(AccessMutation::class)->lock();

            $second->beginTransaction();
            try {
                $second->table('roles')->lockForUpdate()->get();
                $this->fail('A second access mutation passed the held role lock.');
            } catch (QueryException $exception) {
                $this->assertStringContainsString('lock timeout', strtolower($exception->getMessage()));
            } finally {
                $second->rollBack();
            }

            $first->commit();
            $second->transaction(fn () => $second->table('roles')->lockForUpdate()->get());
        } finally {
            if ($first->transactionLevel() > 0) {
                $first->rollBack();
            }
            DB::setDefaultConnection($original);
            $first->statement('SET search_path TO public');
            $second->statement('SET search_path TO public');
            $first->statement("DROP SCHEMA {$schema} CASCADE");
            DB::purge('pgsql_access_a');
            DB::purge('pgsql_access_b');
        }
    }
}
